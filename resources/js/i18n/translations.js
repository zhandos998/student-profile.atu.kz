export function translateText(value, locale) {
    if (locale !== 'kk' || typeof value !== 'string') {
        return value;
    }

    const trimmed = value.trim();

    if (trimmed === '') {
        return value;
    }

    const translated = kkTranslations[trimmed];

    if (!translated) {
        return value;
    }

    return value.replace(trimmed, translated);
}
